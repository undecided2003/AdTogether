import { randomUUID } from 'crypto';
import { NextResponse } from 'next/server';
import type { DocumentReference, Transaction } from 'firebase-admin/firestore';
import { adminDb as db, FieldValue } from '@/lib/firebase-admin';
import { authenticatedUid } from '@/lib/request-auth';
import { invalidatePublisherCache } from '@/lib/publisher-app-id';

export const runtime = 'nodejs';

function validLabel(value: unknown): string | null {
  if (typeof value !== 'string') return null;
  const label = value.trim();
  return label.length >= 1 && label.length <= 120 ? label : null;
}

function validAppId(value: unknown): value is string {
  // New IDs are generated by this route, but existing accounts can have
  // legacy IDs. The ownership check inside each transaction is authoritative.
  return typeof value === 'string' && value.length >= 1 && value.length <= 1_500;
}

function storedAppIds(userData: Record<string, unknown>): string[] {
  return Array.isArray(userData.appIds)
    ? userData.appIds.filter(validAppId)
    : [];
}

function isLegacyAppId(userData: Record<string, unknown>, appId: string): boolean {
  return userData.appId === appId ||
    userData.apiKey === appId ||
    (Array.isArray(userData.apiKeys) && userData.apiKeys.includes(appId));
}

export async function POST(request: Request) {
  const uid = await authenticatedUid(request);
  if (!uid) return NextResponse.json({ error: 'Authentication is required' }, { status: 401 });

  let body: { label?: unknown };
  try {
    body = await request.json();
  } catch {
    return NextResponse.json({ error: 'Invalid request body' }, { status: 400 });
  }

  const label = validLabel(body.label);
  if (!label) return NextResponse.json({ error: 'A label between 1 and 120 characters is required' }, { status: 400 });

  const appId = 'at_' + randomUUID().replace(/-/g, '');
  const userRef = db.collection('users').doc(uid) as DocumentReference;
  let created = false;

  await db.runTransaction(async (transaction: Transaction) => {
    const userSnap = await transaction.get(userRef);
    if (!userSnap.exists) {
      transaction.set(userRef, {
        uid,
        email: '',
        credits: 75,
        country: 'Unknown',
        appIds: [appId],
        appIdLabels: { [appId]: label },
        creditNotificationStage: 'none',
        createdAt: new Date().toISOString(),
      });
      created = true;
      return;
    }
    const userData = userSnap.data() || {};
    const existingIds = Array.isArray(userData.appIds)
      ? userData.appIds.filter((value: unknown): value is string => typeof value === 'string')
      : (typeof userData.appId === 'string' ? [userData.appId] : []);
    if (existingIds.includes(appId)) return;

    const labels = userData.appIdLabels && typeof userData.appIdLabels === 'object' &&
      !Array.isArray(userData.appIdLabels)
      ? userData.appIdLabels
      : {};
    transaction.update(userRef, {
      appIds: [...existingIds, appId],
      appIdLabels: { ...labels, [appId]: label },
    });
    created = true;
  });

  if (!created) return NextResponse.json({ error: 'User profile was not found' }, { status: 409 });
  invalidatePublisherCache(appId);
  return NextResponse.json({ appId, label }, { status: 201 });
}

export async function PATCH(request: Request) {
  const uid = await authenticatedUid(request);
  if (!uid) return NextResponse.json({ error: 'Authentication is required' }, { status: 401 });

  let body: { appId?: unknown; label?: unknown };
  try {
    body = await request.json();
  } catch {
    return NextResponse.json({ error: 'Invalid request body' }, { status: 400 });
  }

  const appId = body.appId;
  const label = validLabel(body.label);
  if (!validAppId(appId) || !label) {
    return NextResponse.json({ error: 'A valid App ID and label are required' }, { status: 400 });
  }

  const userRef = db.collection('users').doc(uid) as DocumentReference;
  let updated = false;
  await db.runTransaction(async (transaction: Transaction) => {
    const userSnap = await transaction.get(userRef);
    const userData = userSnap.data() || {};
    if (!userSnap.exists) return;
    const appIds = storedAppIds(userData);
    if (!appIds.includes(appId) && !isLegacyAppId(userData, appId)) return;
    const labels = userData.appIdLabels && typeof userData.appIdLabels === 'object' &&
      !Array.isArray(userData.appIdLabels)
      ? userData.appIdLabels
      : {};
    transaction.update(userRef, {
      // Preserve a legacy public identifier while migrating it into the
      // current shape so later dashboard operations address the same ID.
      appIds: appIds.includes(appId) ? appIds : [...appIds, appId],
      appIdLabels: { ...labels, [appId]: label },
    });
    updated = true;
  });

  if (!updated) return NextResponse.json({ error: 'App ID was not found' }, { status: 404 });
  invalidatePublisherCache(appId);
  return NextResponse.json({ appId, label });
}

export async function DELETE(request: Request) {
  const uid = await authenticatedUid(request);
  if (!uid) return NextResponse.json({ error: 'Authentication is required' }, { status: 401 });

  let body: { appId?: unknown };
  try {
    body = await request.json();
  } catch {
    return NextResponse.json({ error: 'Invalid request body' }, { status: 400 });
  }
  const appId = body.appId;
  if (!validAppId(appId)) return NextResponse.json({ error: 'A valid App ID is required' }, { status: 400 });

  const userRef = db.collection('users').doc(uid) as DocumentReference;
  let deleted = false;
  await db.runTransaction(async (transaction: Transaction) => {
    const userSnap = await transaction.get(userRef);
    const userData = userSnap.data() || {};
    if (!userSnap.exists) return;
    const appIds = storedAppIds(userData);
    if (!appIds.includes(appId) && !isLegacyAppId(userData, appId)) return;
    const labels = userData.appIdLabels && typeof userData.appIdLabels === 'object' &&
      !Array.isArray(userData.appIdLabels)
      ? { ...userData.appIdLabels }
      : {};
    delete labels[appId];
    const changes: Record<string, unknown> = {
      appIds: appIds.filter((value) => value !== appId),
      appIdLabels: labels,
    };
    // Public App IDs are resolved from both current and legacy fields. Remove
    // every matching legacy representation, or the supposedly deleted ID
    // would keep serving ads.
    if (userData.appId === appId) changes.appId = FieldValue.delete();
    if (userData.apiKey === appId) changes.apiKey = FieldValue.delete();
    if (Array.isArray(userData.apiKeys) && userData.apiKeys.includes(appId)) {
      changes.apiKeys = userData.apiKeys.filter((value: unknown) => value !== appId);
    }
    transaction.update(userRef, changes);
    deleted = true;
  });

  if (!deleted) return NextResponse.json({ error: 'App ID was not found' }, { status: 404 });
  invalidatePublisherCache(appId);
  return NextResponse.json({ success: true });
}
